import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
import { createRequire } from 'node:module';
const pw = createRequire(import.meta.url)('/opt/node-tools/node_modules/playwright');
const DIST = path.resolve('dist');
const s = http.createServer((q, r) => { const p = decodeURIComponent(new URL(q.url, 'http://x').pathname); let f = path.join(DIST, p); if (!path.extname(p)) f += '.html'; if (!fs.existsSync(f)) { r.writeHead(404); r.end(); return; } r.writeHead(200, { 'content-type': f.endsWith('.js') || f.endsWith('.mjs') ? 'text/javascript' : f.endsWith('.css') ? 'text/css' : 'text/html' }); fs.createReadStream(f).pipe(r); });
await new Promise((r) => s.listen(4395, r));
const b = await pw.chromium.launch();
const pg = await b.newPage({ viewport: { width: 1280, height: 900 } });
pg.on('console', (m) => console.log('console', m.type(), m.text().slice(0, 200)));
pg.on('pageerror', (e) => console.log('pageerror', e.message));
await pg.goto('http://localhost:4395/edit-pdf');
await pg.setInputFiles('#ep-drop input[type=file]', 'tests/fixtures/generated/a.pdf');
await pg.waitForSelector('.ov-page canvas');
const box = await pg.locator('.ov-page').first().boundingBox();
console.log('box', box);
const hit = await pg.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e ? e.className + ' ' + e.tagName : 'none'; }, [box.x + box.width * 0.2, box.y + box.height * 0.3]);
console.log('hit', hit);
await pg.mouse.click(box.x + box.width * 0.2, box.y + box.height * 0.3);
await pg.waitForTimeout(500);
console.log('items', await pg.$$eval('.ov-item', (x) => x.length));
await b.close(); s.close();
